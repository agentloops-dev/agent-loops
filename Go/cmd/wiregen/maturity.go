package main

import (
	"encoding/json"
	"fmt"
	"strings"
)

// Early is one capability that is not GA, as Packages/Wire/maturity.json lists it (#6052): its
// level, the name of its feature, its issue, and the clients that show it during a pilot. A
// capability that the list does not name is GA.
type Early struct {
	Capability string   `json:"capability"`
	Level      string   `json:"level"`
	Title      string   `json:"title"`
	Issue      int      `json:"issue"`
	Clients    []string `json:"clients,omitempty"`
}

// The levels of a capability that is not GA, in order: GA is the absence from the list.
var earlyLevels = map[string]bool{"pilot": true, "alpha": true, "beta": true}

// The clients a capability can name.
var earlyClients = map[string]bool{"mac": true, "remote": true, "web": true}

// readMaturity reads the list and checks it against the capabilities the documents name: each
// one known, once, in name order, at pilot, alpha or beta, with a title and an issue, and only
// mac, remote and web as its clients, each once.
func readMaturity(b []byte, known []string) ([]Early, error) {
	var file struct {
		Capabilities []Early `json:"capabilities"`
	}
	if err := json.Unmarshal(b, &file); err != nil {
		return nil, err
	}
	isKnown := map[string]bool{}
	for _, c := range known {
		isKnown[c] = true
	}
	names := make([]string, 0, len(file.Capabilities))
	seen := map[string]bool{}
	for _, e := range file.Capabilities {
		switch {
		case !isKnown[e.Capability]:
			return nil, fmt.Errorf("capability %q is not one that Packages/Wire names", e.Capability)
		case seen[e.Capability]:
			return nil, fmt.Errorf("capability %q is listed twice", e.Capability)
		case !earlyLevels[e.Level]:
			return nil, fmt.Errorf("capability %q: the level is pilot, alpha or beta (leave a GA capability out), not %q", e.Capability, e.Level)
		case strings.TrimSpace(e.Title) == "":
			return nil, fmt.Errorf("capability %q needs the title of its feature", e.Capability)
		case e.Issue <= 0:
			return nil, fmt.Errorf("capability %q needs its issue", e.Capability)
		}
		named := map[string]bool{}
		for _, c := range e.Clients {
			if !earlyClients[c] || named[c] {
				return nil, fmt.Errorf("capability %q: its clients are mac, remote and web, each once, not %q", e.Capability, c)
			}
			named[c] = true
		}
		seen[e.Capability] = true
		names = append(names, e.Capability)
	}
	if err := inNameOrder("capabilities", names); err != nil {
		return nil, err
	}
	return file.Capabilities, nil
}

// swiftMaturity is AgentsKitCore's Maturity.generated.swift: the list as data. Maturity.swift,
// by hand, says how a client reads it.
func swiftMaturity(list []Early) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
// swiftlint:disable all

extension EarlyFeature {
    /// Each capability that is not GA, from Packages/Wire/maturity.json (#6052), in name order.
    /// A capability that is not here is GA. Maturity.swift says how a client reads it.
    public static let all: [EarlyFeature] = [
`)
	for _, e := range list {
		clients := "nil"
		if len(e.Clients) > 0 {
			parts := make([]string, len(e.Clients))
			for i, c := range e.Clients {
				parts[i] = "." + c
			}
			clients = "[" + strings.Join(parts, ", ") + "]"
		}
		fmt.Fprintf(&b, "        EarlyFeature(capability: %q, level: .%s, title: %q, issue: %d, clients: %s),\n",
			e.Capability, e.Level, e.Title, e.Issue, clients)
	}
	b.WriteString("    ]\n}\n")
	return b.String()
}

// tsMaturity is Web/src/protocol/maturity.generated.ts.
func tsMaturity(list []Early) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
//
// Each capability that is not GA, from Packages/Wire/maturity.json (#6052), in name order. A
// capability that is not here is GA. model/maturity.ts says how the page reads it.

export type EarlyLevel = "pilot" | "alpha" | "beta";
export type EarlyClient = "mac" | "remote" | "web";

export interface EarlyFeatureInfo {
  readonly capability: string;
  readonly level: EarlyLevel;
  readonly title: string;
  readonly issue: number;
  readonly clients?: readonly EarlyClient[];
}

export const earlyFeatures: readonly EarlyFeatureInfo[] = [
`)
	for _, e := range list {
		clients := ""
		if len(e.Clients) > 0 {
			q, _ := json.Marshal(e.Clients)
			clients = fmt.Sprintf(", clients: %s", strings.ReplaceAll(string(q), ",", ", "))
		}
		fmt.Fprintf(&b, "  { capability: %q, level: %q, title: %q, issue: %d%s },\n", e.Capability, e.Level, e.Title, e.Issue, clients)
	}
	b.WriteString("];\n")
	return b.String()
}

