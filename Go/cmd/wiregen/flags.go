package main

import (
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
)

// Flag is one feature flag in work, as Packages/Wire/feature-flags.json lists it (#6254).
type Flag struct {
	Name  string `json:"name"`
	Title string `json:"title"`
	About string `json:"about"`
	Issue int    `json:"issue"`
}

// flagName is the form of a flag's name: words in lower case, with hyphens.
var flagName = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)

// readFlags reads the list and checks it: a name of the right form, once, in name order, and
// a title, a line and an issue for each.
func readFlags(b []byte) ([]Flag, error) {
	var file struct {
		Flags []Flag `json:"flags"`
	}
	if err := json.Unmarshal(b, &file); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(file.Flags))
	seen := map[string]bool{}
	for _, f := range file.Flags {
		switch {
		case !flagName.MatchString(f.Name):
			return nil, fmt.Errorf("flag %q: a name is words in lower case with hyphens", f.Name)
		case seen[f.Name]:
			return nil, fmt.Errorf("flag %q is listed twice", f.Name)
		case strings.TrimSpace(f.Title) == "" || strings.TrimSpace(f.About) == "":
			return nil, fmt.Errorf("flag %q needs a title and an about line", f.Name)
		case f.Issue <= 0:
			return nil, fmt.Errorf("flag %q needs its issue", f.Name)
		}
		seen[f.Name] = true
		names = append(names, f.Name)
	}
	if err := inNameOrder("flags", names); err != nil {
		return nil, err
	}
	return file.Flags, nil
}

// swiftFlags is AgentsKitCore's FeatureFlag.generated.swift: a case per flag, with its words.
// The store (FeatureFlag.swift) is written by hand.
func swiftFlags(flags []Flag) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
// swiftlint:disable all

/// The feature flags in work, from Packages/Wire/feature-flags.json (#6254). FeatureFlag.swift
/// says where each one is kept and how a client reads it.
public enum FeatureFlag: String, CaseIterable, Sendable {
`)
	for _, f := range flags {
		fmt.Fprintf(&b, "    /// %s (#%d).\n    case %s = %q\n", f.Title, f.Issue, capabilityWord(f.Name), f.Name)
	}
	words := func(name string, of func(Flag) string) {
		fmt.Fprintf(&b, "\n    public var %s: String {\n        switch self {\n", name)
		for _, f := range flags {
			fmt.Fprintf(&b, "        case .%s: %q\n", capabilityWord(f.Name), of(f))
		}
		b.WriteString("        }\n    }\n")
	}
	if len(flags) > 0 {
		b.WriteString("\n    /// What Settings calls it.")
		words("title", func(f Flag) string { return f.Title })
		b.WriteString("\n    /// What it turns on, in one line.")
		words("about", func(f Flag) string { return f.About })
		b.WriteString("\n    /// The issue of the feature in work.\n    public var issue: Int {\n        switch self {\n")
		for _, f := range flags {
			fmt.Fprintf(&b, "        case .%s: %d\n", capabilityWord(f.Name), f.Issue)
		}
		b.WriteString("        }\n    }\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// tsFlags is Web/src/protocol/flags.generated.ts.
func tsFlags(flags []Flag) string {
	var b strings.Builder
	b.WriteString(`// GENERATED by scripts/wire.sh gen (Go/cmd/wiregen) from Packages/Wire. Do not edit.
//
// The feature flags in work, from Packages/Wire/feature-flags.json (#6254). model/featureFlags.ts
// says where each one is kept and how the page reads it.

export interface FeatureFlagInfo {
  readonly name: string;
  readonly title: string;
  readonly about: string;
  readonly issue: number;
}

export const featureFlags: readonly FeatureFlagInfo[] = [
`)
	for _, f := range flags {
		fmt.Fprintf(&b, "  { name: %q, title: %q, about: %q, issue: %d },\n", f.Name, f.Title, f.About, f.Issue)
	}
	b.WriteString("];\n")
	return b.String()
}
